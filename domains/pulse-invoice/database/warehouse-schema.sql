-- Canonical data contract for the Pulse Invoice pilot.
-- This migration creates schema, tables and aggregate views only; it does not
-- import or modify any invoice records.

BEGIN;

CREATE SCHEMA IF NOT EXISTS pulse_invoice;

CREATE TABLE IF NOT EXISTS pulse_invoice.extraction_runs (
    run_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_key TEXT NOT NULL,
    source_system TEXT NOT NULL DEFAULT 'pulse-archive',
    source_document_id BIGINT NOT NULL,
    source_sha256 CHAR(64) NOT NULL,
    pipeline_version TEXT NOT NULL,
    layout_family TEXT NOT NULL DEFAULT 'unclassified',
    run_status TEXT NOT NULL CHECK (run_status IN (
        'queued', 'running', 'succeeded', 'needs_review', 'failed', 'cancelled'
    )),
    extractor_mode TEXT NOT NULL DEFAULT 'local',
    extractor_name TEXT,
    attempt INTEGER NOT NULL DEFAULT 1 CHECK (attempt > 0),
    started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at TIMESTAMPTZ,
    duration_ms BIGINT,
    cost_usd NUMERIC(14, 6),
    error_code TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_extraction_runs_run_tenant UNIQUE (run_id, tenant_key),
    UNIQUE (tenant_key, source_system, source_document_id, source_sha256, pipeline_version, attempt)
);

CREATE TABLE IF NOT EXISTS pulse_invoice.invoices (
    invoice_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_key TEXT NOT NULL,
    source_system TEXT NOT NULL DEFAULT 'pulse-archive',
    source_document_id BIGINT NOT NULL,
    source_sha256 CHAR(64) NOT NULL,
    extraction_run_id UUID,
    document_type TEXT NOT NULL DEFAULT 'nfse',
    invoice_number TEXT,
    series TEXT,
    verification_code TEXT,
    issuer_name TEXT,
    issuer_tax_id TEXT,
    recipient_name TEXT,
    recipient_tax_id TEXT,
    service_code TEXT,
    service_description TEXT,
    issue_date DATE,
    competence_date DATE,
    due_date DATE,
    payment_date DATE,
    currency CHAR(3) NOT NULL DEFAULT 'BRL',
    amount_gross NUMERIC(18, 2),
    amount_deductions NUMERIC(18, 2),
    tax_iss NUMERIC(18, 2),
    iss_rate_percent NUMERIC(8, 5),
    tax_pis NUMERIC(18, 2),
    tax_cofins NUMERIC(18, 2),
    tax_irrf NUMERIC(18, 2),
    tax_inss NUMERIC(18, 2),
    amount_total NUMERIC(18, 2),
    review_status TEXT NOT NULL DEFAULT 'pending_review' CHECK (review_status IN (
        'pending_review', 'approved', 'rejected', 'error'
    )),
    payment_status TEXT NOT NULL DEFAULT 'unknown' CHECK (payment_status IN (
        'unknown', 'open', 'partial', 'paid', 'overdue'
    )),
    field_confidence JSONB NOT NULL DEFAULT '{}'::jsonb,
    source_pages JSONB NOT NULL DEFAULT '{}'::jsonb,
    reviewed_by TEXT,
    reviewed_at TIMESTAMPTZ,
    approved_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_invoices_id_tenant UNIQUE (invoice_id, tenant_key),
    CONSTRAINT fk_invoices_run_tenant FOREIGN KEY (extraction_run_id, tenant_key)
        REFERENCES pulse_invoice.extraction_runs(run_id, tenant_key),
    UNIQUE (tenant_key, source_system, source_document_id)
);

-- Keep an existing pilot schema compatible when this canonical DDL is reapplied.
ALTER TABLE pulse_invoice.invoices
    ADD COLUMN IF NOT EXISTS payment_date DATE;

CREATE TABLE IF NOT EXISTS pulse_invoice.invoice_lines (
    invoice_id BIGINT NOT NULL,
    tenant_key TEXT NOT NULL,
    line_number INTEGER NOT NULL CHECK (line_number > 0),
    service_code TEXT,
    description TEXT,
    quantity NUMERIC(18, 4),
    unit_amount NUMERIC(18, 4),
    amount_total NUMERIC(18, 2),
    tax_code TEXT,
    tax_rate NUMERIC(8, 5),
    tax_amount NUMERIC(18, 2),
    source_page INTEGER,
    PRIMARY KEY (invoice_id, line_number),
    CONSTRAINT fk_invoice_lines_invoice_tenant FOREIGN KEY (invoice_id, tenant_key)
        REFERENCES pulse_invoice.invoices(invoice_id, tenant_key) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS pulse_invoice.review_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT NOT NULL,
    tenant_key TEXT NOT NULL,
    actor_id TEXT,
    from_status TEXT,
    to_status TEXT NOT NULL,
    changed_fields TEXT[] NOT NULL DEFAULT '{}',
    event_payload JSONB NOT NULL DEFAULT '{}'::jsonb,
    event_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_review_events_invoice_tenant FOREIGN KEY (invoice_id, tenant_key)
        REFERENCES pulse_invoice.invoices(invoice_id, tenant_key) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_invoice_tenant_status
    ON pulse_invoice.invoices (tenant_key, review_status);
CREATE INDEX IF NOT EXISTS idx_invoice_tenant_issue_date
    ON pulse_invoice.invoices (tenant_key, issue_date);
CREATE INDEX IF NOT EXISTS idx_invoice_tenant_due_date
    ON pulse_invoice.invoices (tenant_key, due_date);
CREATE INDEX IF NOT EXISTS idx_invoice_supplier_reference
    ON pulse_invoice.invoices (tenant_key, issuer_tax_id, invoice_number, series, issue_date);
CREATE INDEX IF NOT EXISTS idx_invoice_runs_source
    ON pulse_invoice.extraction_runs (tenant_key, source_document_id, started_at DESC);

-- Aggregate views for later Grafana/Portal use. Grafana should receive SELECT
-- only on approved reporting views, never on the PII-bearing base tables.
CREATE OR REPLACE VIEW pulse_invoice.v_dashboard_monthly
WITH (security_invoker = true) AS
SELECT tenant_key,
       date_trunc('month', issue_date)::date AS invoice_month,
       currency,
       count(*) FILTER (WHERE review_status = 'approved') AS approved_count,
       count(*) FILTER (WHERE review_status = 'pending_review') AS pending_review_count,
       count(*) FILTER (WHERE review_status = 'rejected') AS rejected_count,
       coalesce(sum(amount_total) FILTER (WHERE review_status = 'approved'), 0)::NUMERIC(18, 2) AS approved_total
FROM pulse_invoice.invoices
WHERE issue_date IS NOT NULL
GROUP BY tenant_key, date_trunc('month', issue_date)::date, currency;

CREATE OR REPLACE VIEW pulse_invoice.v_dashboard_review_queue
WITH (security_invoker = true) AS
SELECT tenant_key, review_status, count(*) AS invoice_count
FROM pulse_invoice.invoices
GROUP BY tenant_key, review_status;

CREATE OR REPLACE VIEW pulse_invoice.v_dashboard_due_dates
WITH (security_invoker = true) AS
SELECT tenant_key,
       due_date,
       currency,
       count(*) AS invoice_count,
       coalesce(sum(amount_total), 0)::NUMERIC(18, 2) AS amount_total
FROM pulse_invoice.invoices
WHERE review_status = 'approved'
  AND payment_status IN ('unknown', 'open', 'partial', 'overdue')
  AND due_date IS NOT NULL
GROUP BY tenant_key, due_date, currency;

COMMIT;
